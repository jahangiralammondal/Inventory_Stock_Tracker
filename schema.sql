CREATE TABLE IF NOT EXISTS users (
 id INT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(80) UNIQUE NOT NULL,
 name VARCHAR(100) NOT NULL, role ENUM('Admin','Staff','Supplier','Buyer') NOT NULL,
 password_hash VARCHAR(255) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 sku VARCHAR(40) PRIMARY KEY, name VARCHAR(100) NOT NULL, category VARCHAR(80) NOT NULL,
 aisle INT NOT NULL, bin_no INT NOT NULL, qty INT NOT NULL DEFAULT 0,
 minimum INT NOT NULL, cost DECIMAL(10,2) NOT NULL, price DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS movements (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, ticket CHAR(32) UNIQUE NOT NULL, sku VARCHAR(40) NOT NULL,
 kind VARCHAR(30) NOT NULL, units INT NOT NULL, balance INT NOT NULL, delta INT NOT NULL,
 actor INT NOT NULL, partner INT, original_id BIGINT, note VARCHAR(240) NOT NULL,
 price DECIMAL(10,2) NOT NULL, discount DECIMAL(5,2) NOT NULL, tax DECIMAL(5,2) NOT NULL,
 created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(sku) REFERENCES products(sku), FOREIGN KEY(actor) REFERENCES users(id),
 FOREIGN KEY(partner) REFERENCES users(id), FOREIGN KEY(original_id) REFERENCES movements(id)
) ENGINE=InnoDB;
